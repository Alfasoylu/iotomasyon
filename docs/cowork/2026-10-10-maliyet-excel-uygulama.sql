CREATE TEMP TABLE _ch(sku text, alan text, eski text, yeni text, satir int, guven text) ON COMMIT DROP;
WITH cur AS (SELECT p."sourceCostRmb" r, p."weightKg" k, p."customsRatePct" c, p.gtip1 g, p."importPaymentFeePct" f, p."shippingMethodPref" s, m.*
               FROM public."Product" p JOIN _mx m ON m.sku = p.sku)
INSERT INTO _ch
SELECT sku, 'sourceCostRmb', r::text, rmb::text, satir, guven FROM cur WHERE rmb IS NOT NULL AND round(r, 2) IS NOT DISTINCT FROM rmb_eski AND r IS DISTINCT FROM rmb
UNION ALL SELECT sku, 'weightKg', k::text, kg::text, satir, guven FROM cur WHERE kg IS NOT NULL AND round(k, 3) IS NOT DISTINCT FROM kg_eski AND k IS DISTINCT FROM kg
UNION ALL SELECT sku, 'customsRatePct', c::text, gum::text, satir, guven FROM cur WHERE gum IS NOT NULL AND round(c, 2) IS NOT DISTINCT FROM gum_eski AND c IS DISTINCT FROM gum
UNION ALL SELECT sku, 'gtip1', g, gtip, satir, guven FROM cur WHERE gtip IS NOT NULL AND g IS NOT DISTINCT FROM gtip_eski AND g IS DISTINCT FROM gtip
UNION ALL SELECT sku, 'importPaymentFeePct', f::text, '5', satir, guven FROM cur WHERE f IS DISTINCT FROM 5
UNION ALL SELECT sku, 'shippingMethodPref', s, NULL, satir, guven FROM cur WHERE s IS NOT NULL;

UPDATE public."Product" p SET
  "sourceCostRmb" = CASE WHEN EXISTS (SELECT 1 FROM _ch WHERE _ch.sku = p.sku AND alan = 'sourceCostRmb') THEN m.rmb ELSE p."sourceCostRmb" END,
  "weightKg" = CASE WHEN EXISTS (SELECT 1 FROM _ch WHERE _ch.sku = p.sku AND alan = 'weightKg') THEN m.kg ELSE p."weightKg" END,
  "customsRatePct" = CASE WHEN EXISTS (SELECT 1 FROM _ch WHERE _ch.sku = p.sku AND alan = 'customsRatePct') THEN m.gum ELSE p."customsRatePct" END,
  gtip1 = CASE WHEN EXISTS (SELECT 1 FROM _ch WHERE _ch.sku = p.sku AND alan = 'gtip1') THEN m.gtip ELSE p.gtip1 END,
  "importPaymentFeePct" = 5,
  "shippingMethodPref" = NULL,
  "updatedAt" = now()
FROM _mx m WHERE m.sku = p.sku AND EXISTS (SELECT 1 FROM _ch WHERE _ch.sku = p.sku);

